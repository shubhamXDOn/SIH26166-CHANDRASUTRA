def test_register_real_pair_is_gated_and_idempotent(tmp_path, settings_factory):
    from backend.app.pairs import PairRegistry, register_real_pair

    fixturegen.write_real_shaped_pair(tmp_path)
    settings = _make_settings(tmp_path, settings_factory)

    r1 = register_real_pair(
        settings, image_a_rel="raw/ohrc/ch2_ohr_ncp_20211228T2209123959_c_img_d18.img",
        image_b_rel="raw/tmc2/ch2_tmc_ncn_20200207T0716469418_c_img_d18.img",
    )
    assert r1.data_source_gate == "PATH_A_REAL_DATA"
    assert r1.source_class_a == "REAL_PRADAN"
    assert r1.source_class_b == "REAL_PRADAN"
    assert r1.overlap_status == "CONFIRMED_OVERLAP"
    assert r1.overlap_evidence.startswith("footprint_bbox_intersection")

    r2 = register_real_pair(
        settings, image_a_rel="raw/ohrc/ch2_ohr_ncp_20211228T2209123959_c_img_d18.img",
        image_b_rel="raw/tmc2/ch2_tmc_ncn_20200207T0716469418_c_img_d18.img",
    )
    assert r2.pair_id == r1.pair_id  # idempotent, not duplicated
    all_ids = [r.pair_id for r in PairRegistry(settings).list()]
    assert all_ids.count(r1.pair_id) == 1


