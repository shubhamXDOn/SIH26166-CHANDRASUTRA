def test_api_auto_register_real_pair(tmp_path):
    client, settings = _api_harness(tmp_path)
    fixturegen.write_real_shaped_pair(tmp_path)

    r = client.post("/api/pairs/auto-register", json={})
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["registered"] is True
    assert body["gate"] == "PATH_A_REAL_DATA"
    assert body["validation"]["status"] == "VALID"

    scan = client.get("/api/pairs/real-data/scan")
    assert scan.status_code == 200
    scan_body = scan.json()
    assert scan_body["source_breakdown"]["REAL_PRADAN"] == 2
    assert scan_body["selected_ohrc"] is not None
    assert scan_body["selected_tmc2"] is not None

    root_status = client.get("/api/data/status")
    assert root_status.status_code == 200
    ds = root_status.json()["data_source"]
    assert ds["requirements_met"] is True
    assert body["pair_id"] in ds["registered_real_pair_ids"]


